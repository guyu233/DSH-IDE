/**
 * One-time CSS-module merger for the sidecar chat renderer.
 *
 * Reads the 8 CSS modules from the AUTHORITATIVE read-only source
 * (E:/deepseek-harness-0.2.2-rc.1/packages/client/ui-chat/src/client/chat/) and emits:
 *   - dsh-chat.css          : every rule, with each module's local class names
 *                            prefixed (dsh-<module>-<class>) so `.root` from
 *                            ChatView cannot collide with `.root` from
 *                            ReasoningRow; `:global(...)` unwrapped.
 *   - shims/cssClasses.ts   : one exported class-map object per module,
 *                            consumed by the copied .tsx files.
 *
 * The running-whale APNG is inlined as a data URL so no extra asset is needed
 * in dist/ (see README.md and PROVENANCE.md). It is copied verbatim to
 * assets/running-whale@2x.png as well for provenance/audit.
 *
 * This script is a REGENERATION helper, not part of the runtime build:
 * build-render.mjs only consumes the two checked-in outputs, so `npm pack`
 * never needs E:/deepseek-harness* to be present.
 *
 * Usage (from repo root, requires the read-only source checkout):
 *   node build/dsh/chat-render/build-css.mjs
 */

import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = HERE
const SRC = 'E:/deepseek-harness-0.2.2-rc.1/packages/client/ui-chat/src/client/chat'
const OUT_CSS = path.join(ROOT, 'dsh-chat.css')
const OUT_MAP = path.join(ROOT, 'shims/cssClasses.ts')

/** module filename -> class-map export name (must match build-render rewrite). */
const MODULES = [
  ['accessibility.module.css', 'a11y'],
  ['ReasoningRow.module.css', 'reasoningRow'],
  ['AssistantMarkdown.module.css', 'assistantMarkdown'],
  ['MessageItem.module.css', 'messageItem'],
  ['StatsPills.module.css', 'statsPills'],
  ['stat-dialog.module.css', 'statDialog'],
  ['TurnUsagePanel.module.css', 'turnUsagePanel'],
  ['ChatView.module.css', 'chatView'],
]

/** Extract local class names from a CSS module (definitions only). */
function classNames(css) {
  const names = new Set()
  const stripped = css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/:global\([^)]*\)/g, '')
  for (const m of stripped.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) names.add(m[1])
  return [...names].sort()
}

/**
 * Rewrite one module's CSS:
 *  - protect comments, strings, and :global(...) bodies in placeholders;
 *  - prefix remaining `.class` tokens;
 *  - restore placeholders (unwrapping :global).
 */
function prefixCss(css, prefix, dataUrl) {
  const stores = { global: [], comment: [], string: [] }
  let work = css

  work = work.replace(/\/\*[\s\S]*?\*\//g, m => {
    stores.comment.push(m)
    return `\u0000C${stores.comment.length - 1}\u0000`
  })
  work = work.replace(/:global\(([^)]*)\)/g, (_m, inner) => {
    stores.global.push(inner)
    return `\u0000G${stores.global.length - 1}\u0000`
  })
  // Inline the APNG BEFORE protecting strings. In 0.2.2-rc.1 the asset moved to
  // src/client/assets/ and ChatView.module.css references url('../assets/running-whale@2x.png');
  // older checkouts used url('./running-whale@2x.png'). Handle both, quoted or not.
  work = work.replace(/url\(['"]?\.\.?\/assets\/running-whale@2x\.png['"]?\)/g, `url("${dataUrl}")`)
  work = work.replace(/url\(['"]?\.\/running-whale@2x\.png['"]?\)/g, `url("${dataUrl}")`)

  work = work.replace(/'[^']*'|"[^"]*"/g, m => {
    stores.string.push(m)
    return `\u0000S${stores.string.length - 1}\u0000`
  })

  work = work.replace(/\.(-?[_a-zA-Z][\w-]*)/g, (_m, name) => `.${prefix}${name}`)

  work = work.replace(/\u0000S(\d+)\u0000/g, (_m, i) => stores.string[Number(i)])
  work = work.replace(/\u0000G(\d+)\u0000/g, (_m, i) => stores.global[Number(i)])
  work = work.replace(/\u0000C(\d+)\u0000/g, (_m, i) => stores.comment[Number(i)])
  return work
}

const pngPath = path.join(SRC, '../assets/running-whale@2x.png')
const png = fs.readFileSync(pngPath)
const pngSha = createHash('sha256').update(png).digest('hex')
const dataUrl = `data:image/png;base64,${png.toString('base64')}`
const ASSETS = path.join(ROOT, 'assets')
fs.mkdirSync(ASSETS, { recursive: true })
fs.writeFileSync(path.join(ASSETS, 'running-whale@2x.png'), png)

const cssParts = []
const mapParts = []
const shaLines = []

cssParts.push(`/*\n * dsh-chat.css - merged CSS modules from @deepseek-ai/dsh-client-ui-chat 0.2.2-rc.1\n * Source: E:/deepseek-harness-0.2.2-rc.1/packages/client/ui-chat/src/client/chat/*.module.css\n * Generated by build/dsh/chat-render/build-css.mjs (regeneration helper).\n * Class names are prefixed per source module; :global(...) selectors are unwrapped.\n * Inlined asset: running-whale@2x.png sha256=${pngSha}\n * See PROVENANCE.md for the per-file digests. DO NOT EDIT BY HAND.\n */\n`)

for (const [file, key] of MODULES) {
  const src = fs.readFileSync(path.join(SRC, file), 'utf8')
  shaLines.push(`${file}\0${createHash('sha256').update(Buffer.from(src, 'utf8')).digest('hex')}`)
  const prefix = `dsh-${key}-`
  const names = classNames(src)
  cssParts.push(`\n/* ===== ${file} -> .${prefix}* ===== */\n${prefixCss(src, prefix, dataUrl).trim()}\n`)
  const entries = names.map(n => `  ${/^[_a-zA-Z][\w-]*$/.test(n) ? n : JSON.stringify(n)}: '${prefix}${n}',`).join('\n')
  mapParts.push(`/** Classes from ${file}. */\nexport const ${key}: Readonly<Record<string, string>> = {\n${entries}\n}\n`)
}

fs.writeFileSync(OUT_CSS, cssParts.join('\n'), 'utf8')
fs.writeFileSync(OUT_MAP,
  `/**\n * Single CSS class map for the sidecar chat renderer.\n * GENERATED by ../build-css.mjs from the authoritative ui-chat CSS modules.\n * The copied .tsx sources import named maps from here instead of importing\n * 8 separate *.module.css files (which would need 8 CSS-module namespaces).\n * DO NOT EDIT BY HAND; see PROVENANCE.md.\n */\n\n${mapParts.join('\n')}`,
  'utf8')

console.log(`Wrote ${path.relative(process.cwd(), OUT_CSS)} (${fs.statSync(OUT_CSS).size} bytes)`)
console.log(`Wrote ${path.relative(process.cwd(), OUT_MAP)} (${fs.statSync(OUT_MAP).size} bytes)`)
console.log(`Inlined running-whale@2x.png sha256=${pngSha}`)
console.log(`CSS tree digest: ${createHash('sha256').update(shaLines.join('\n')).digest('hex')}`)
